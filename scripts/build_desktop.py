#!/usr/bin/env python3
"""Concatenate desktop/src/*.js (sorted) into the single-file desktop/plugin.js the Hermes loader requires."""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "desktop" / "src"
OUT = ROOT / "desktop" / "plugin.js"
HEADER = "// GENERATED by scripts/build_desktop.py from desktop/src/*.js. Do not edit; edit desktop/src and rebuild.\n"


def build() -> str:
    parts = [p.read_text(encoding="utf-8") for p in sorted(SRC.glob("*.js"))]
    return HEADER + "".join(parts)


def main(argv: list[str]) -> int:
    text = build()
    if "--check" in argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print("desktop/plugin.js is stale: run python3 scripts/build_desktop.py")
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
