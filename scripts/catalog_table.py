"""Print the catalog as markdown: one table per category (id, title, tier, target, module).

The README's catalog section is this output, between the BEGIN/END markers. Refresh it with:
    .venv/bin/python scripts/catalog_table.py --write-readme
tests/test_readme.py fails when the README drifts from the shipped catalog.
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from sysadmin import catalog, ops  # noqa: E402,F401

BEGIN = "<!-- BEGIN CATALOG (generated by scripts/catalog_table.py) -->"
END = "<!-- END CATALOG -->"


def render() -> str:
    by_cat: dict[str, list] = {}
    for op in catalog.entries():
        by_cat.setdefault(op.meta["category"], []).append(op)
    lines: list[str] = []
    for cat in catalog.CATEGORIES:
        ops_in = by_cat.get(cat, [])
        if not ops_in:
            continue
        lines += [f"#### {cat} ({len(ops_in)})", "", "| Id | Title | Tier | Target | Module |", "|---|---|---|---|---|"]
        for op in sorted(ops_in, key=lambda o: o.meta["id"]):
            m = op.meta
            lines.append(f"| `{m['id']}` | {m['title']} | {op.tier} | {m['target']} | {m['module']} |")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def block() -> str:
    return f"{BEGIN}\n\n{render()}\n{END}"


def main(argv: list[str]) -> int:
    if "--write-readme" in argv:
        path = ROOT / "README.md"
        text = path.read_text(encoding="utf-8")
        start, stop = text.index(BEGIN), text.index(END) + len(END)
        path.write_text(text[:start] + block() + text[stop:], encoding="utf-8")
        return 0
    sys.stdout.write(render())
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
