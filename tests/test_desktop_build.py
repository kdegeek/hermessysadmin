import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def test_built_bundle_is_fresh():
    r = subprocess.run([sys.executable, str(ROOT / "scripts" / "build_desktop.py"), "--check"],
                       capture_output=True, text=True)
    assert r.returncode == 0, r.stdout + r.stderr


def test_bundle_starts_with_generated_header():
    assert (ROOT / "desktop" / "plugin.js").read_text(encoding="utf-8").startswith("// GENERATED by scripts/build_desktop.py")


def test_sources_exist_and_are_ordered():
    names = sorted(p.name for p in (ROOT / "desktop" / "src").glob("*.js"))
    assert names[0].startswith("01-") and names[-1].startswith("16-")
